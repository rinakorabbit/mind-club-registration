/* ---------- ตัวช่วยเรียก Apps Script ---------- */
async function callApi(action, data, timeoutMs) {
  if (!CONFIG.API_URL || CONFIG.API_URL.indexOf('PASTE_') === 0) {
    const e = new Error('NOT_CONFIGURED'); e.code = 'NOT_CONFIGURED'; throw e;
  }
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), timeoutMs || 45000);
  try {
    // ไม่ตั้ง Content-Type เพื่อให้เป็น "simple request" (ไม่มี preflight) — วิธีมาตรฐานของ Apps Script
    const res = await fetch(CONFIG.API_URL, {
      method: 'POST',
      body: JSON.stringify(Object.assign({ action: action }, data || {})),
      signal: ctrl.signal
    });
    if (!res.ok) throw new Error('HTTP ' + res.status);
    return await res.json();
  } finally {
    clearTimeout(timer);
  }
}

function esc(s) {
  return String(s == null ? '' : s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}
